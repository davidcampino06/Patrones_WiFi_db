-- Least-privilege role (security/rol_aplicacion.sql): the backend can work with the data but never change the
-- schema. Needs a user that can SET ROLE to it (a superuser, as in CI). Skipped otherwise.
\ir _asserts.sql
SELECT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'wifisense_app')
       AND pg_has_role(current_user, 'wifisense_app', 'MEMBER') AS role_testable \gset
\if :role_testable
BEGIN;

-- A table created after running the script, as a future migration would: default privileges must cover it.
CREATE TABLE prueba_migracion_futura (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nota TEXT);

SET LOCAL ROLE wifisense_app;

INSERT INTO locations (name, city) VALUES ('Sede del rol', 'Pasto');
UPDATE locations SET city = 'Ipiales' WHERE name = 'Sede del rol';
SELECT pg_temp.assert_true(
    (SELECT city FROM locations WHERE name = 'Sede del rol') = 'Ipiales',
    'the application role reads, inserts and updates data (identity sequences included)');
DELETE FROM locations WHERE name = 'Sede del rol';
INSERT INTO users (username, email, password_hash, role) VALUES ('Rol.Prueba', 'Rol.Prueba@WiFiSense.local', 'x', 'USER');
SELECT pg_temp.assert_true(
    (SELECT email FROM users WHERE username = 'Rol.Prueba') = 'rol.prueba@wifisense.local',
    'the email trigger also works for the application role');
INSERT INTO prueba_migracion_futura (nota) VALUES ('ok');
SELECT pg_temp.assert_true(
    (SELECT count(*) FROM prueba_migracion_futura) = 1,
    'tables created later by the owner are usable by the application role');

SELECT pg_temp.assert_denied($$CREATE TABLE intrusa (id INT)$$, 'the application role cannot create tables');
SELECT pg_temp.assert_denied($$DROP TABLE alerts$$, 'the application role cannot drop tables');
SELECT pg_temp.assert_denied($$ALTER TABLE users ADD COLUMN puerta_trasera TEXT$$,
                             'the application role cannot change tables');
SELECT pg_temp.assert_denied($$TRUNCATE measurements$$, 'the application role cannot empty a table at once');
SELECT pg_temp.assert_denied($$CREATE ROLE otro_rol$$, 'the application role cannot create roles');

RESET ROLE;
SELECT pg_temp.assert_true(
    (SELECT setting FROM pg_db_role_setting s, unnest(s.setconfig) AS setting
     WHERE s.setrole = 'wifisense_app'::regrole AND setting LIKE 'statement_timeout=%') = 'statement_timeout=30s',
    'a runaway query of the application stops after 30 seconds');
SELECT pg_temp.assert_true(
    NOT (SELECT rolsuper OR rolcreaterole OR rolcreatedb OR rolbypassrls FROM pg_roles WHERE rolname = 'wifisense_app'),
    'the application role has no special powers');

ROLLBACK;
\else
\echo 'SKIPPED: rol_aplicacion_test (run apply.sh --security as a superuser first)'
\endif
