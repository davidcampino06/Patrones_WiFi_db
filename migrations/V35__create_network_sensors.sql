-- Avance 13: the sensor of each team network. It is the same WiFiSense agent the end users install: the team panel
-- shows an 8-character code (15 minutes, one use), the installer exchanges it for the sensor key, and from then on
-- the agent reports measurements, traffic and protocols of that network. As with the agent keys, only the SHA-256 of
-- the key and of the code is stored.
CREATE TABLE network_sensors (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_id    BIGINT      NOT NULL,
    key_hash      CHAR(64)    NOT NULL,
    key_prefix    VARCHAR(12) NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at  TIMESTAMPTZ,
    agent_version VARCHAR(20),
    platform      VARCHAR(20),
    CONSTRAINT fk_network_sensors_network FOREIGN KEY (network_id) REFERENCES networks (id) ON DELETE CASCADE,
    CONSTRAINT uq_network_sensors_network UNIQUE (network_id),
    CONSTRAINT uq_network_sensors_hash UNIQUE (key_hash),
    CONSTRAINT ck_network_sensors_hash CHECK (key_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_network_sensors_prefix CHECK (key_prefix ~ '^wsa_[A-Za-z0-9_-]{4,8}$'),
    CONSTRAINT ck_network_sensors_version CHECK (agent_version IS NULL OR agent_version ~ '^[0-9A-Za-z.+-]{1,20}$')
);

CREATE TABLE network_sensor_pairing_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_id  BIGINT      NOT NULL,
    code_hash   CHAR(64)    NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_network_sensor_pairing_codes_network FOREIGN KEY (network_id) REFERENCES networks (id)
        ON DELETE CASCADE,
    CONSTRAINT uq_network_sensor_pairing_codes_network UNIQUE (network_id),
    CONSTRAINT uq_network_sensor_pairing_codes_hash UNIQUE (code_hash),
    CONSTRAINT ck_network_sensor_pairing_codes_hash CHECK (code_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_network_sensor_pairing_codes_expiry
        CHECK (expires_at > created_at AND expires_at <= created_at + INTERVAL '1 hour')
);

-- Hourly cleanup of expired codes. The unique constraints already index the foreign keys and the lookups by hash.
CREATE INDEX idx_network_sensor_pairing_codes_expires_at ON network_sensor_pairing_codes (expires_at);

COMMENT ON TABLE network_sensors IS
    'Sensor de cada red del equipo: el agente WiFiSense instalado en un computador de esa red. Solo se guarda el SHA-256 de su clave.';
COMMENT ON COLUMN network_sensors.id IS 'Identificador.';
COMMENT ON COLUMN network_sensors.network_id IS 'Red del equipo que mide; un sensor por red.';
COMMENT ON COLUMN network_sensors.key_hash IS 'SHA-256 de la clave del sensor (64 hex). La clave no se puede recuperar.';
COMMENT ON COLUMN network_sensors.key_prefix IS 'Primeros caracteres de la clave, para reconocerla.';
COMMENT ON COLUMN network_sensors.created_at IS 'Momento en que se instaló el sensor.';
COMMENT ON COLUMN network_sensors.last_seen_at IS 'Último reporte del sensor; define si está conectado.';
COMMENT ON COLUMN network_sensors.agent_version IS 'Versión del agente que envió el último reporte.';
COMMENT ON COLUMN network_sensors.platform IS 'Sistema operativo del computador donde corre el sensor.';

COMMENT ON TABLE network_sensor_pairing_codes IS
    'Códigos de 8 caracteres para instalar el sensor de una red del equipo; un uso y 15 minutos. Solo se guarda su SHA-256.';
COMMENT ON COLUMN network_sensor_pairing_codes.id IS 'Identificador.';
COMMENT ON COLUMN network_sensor_pairing_codes.network_id IS 'Red del equipo donde se instalará el sensor; un código vigente por red.';
COMMENT ON COLUMN network_sensor_pairing_codes.code_hash IS 'SHA-256 del código (64 hex).';
COMMENT ON COLUMN network_sensor_pairing_codes.created_at IS 'Momento en que se generó el código.';
COMMENT ON COLUMN network_sensor_pairing_codes.expires_at IS 'Desde este momento el código ya no sirve (máximo una hora).';
