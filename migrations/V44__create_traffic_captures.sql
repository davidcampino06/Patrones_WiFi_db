-- Avance 24: technical traffic captures on a team network, asked by an administrator and run by that network's
-- sensor (the WiFiSense agent on a computer of the network).
--
-- What a capture is, and what it is not:
--   * It sees the traffic that reaches the capture interface of the sensor's computer: its own traffic plus the
--     broadcast and multicast of the network (scenario A). On a normal Wi-Fi it does NOT see what other devices send
--     to Internet; WiFiSense does not use monitor mode and never decrypts anything.
--   * Only headers are read (the first bytes of each packet) and only statistics leave the computer: counts, bytes,
--     protocols, ports and intervals. No address, no MAC and no content is stored here. The raw capture file is
--     deleted on the sensor's computer right after the analysis.
--   * Every capture has limits (seconds, packets, bytes) and a stated purpose, and remembers who asked for it.
--
-- Life: PENDING (asked) -> RUNNING (the sensor started) -> COMPLETED (with its statistics) or FAILED (with the reason).
-- A capture still waiting can be CANCELLED; one already running is stopped by the sensor and ends COMPLETED with
-- stop_reason CANCELLED and the statistics of what it did capture. One capture waiting or running per network.
CREATE TABLE traffic_captures (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_id            BIGINT       NOT NULL REFERENCES networks (id) ON DELETE CASCADE,
    requested_by          BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    purpose               VARCHAR(200) NOT NULL,
    status                VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
    max_seconds           SMALLINT     NOT NULL,
    max_packets           INTEGER      NOT NULL,
    max_bytes             BIGINT       NOT NULL,
    requested_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    started_at            TIMESTAMPTZ,
    finished_at           TIMESTAMPTZ,
    cancel_requested_at   TIMESTAMPTZ,
    failure_reason        VARCHAR(20),
    stop_reason           VARCHAR(14),
    capture_tool          VARCHAR(14),
    interface_name        VARCHAR(64),
    agent_version         VARCHAR(20),
    duration_ms           INTEGER,
    packet_count          INTEGER,
    byte_count            BIGINT,
    dropped_by_tool       INTEGER,
    malformed_packets     INTEGER,
    inbound_bytes         BIGINT,
    outbound_bytes        BIGINT,
    broadcast_packets     INTEGER,
    multicast_packets     INTEGER,
    distinct_local_hosts  SMALLINT,
    distinct_remote_hosts INTEGER,
    analyzed_with         VARCHAR(6),
    CONSTRAINT ck_traffic_captures_purpose CHECK (length(btrim(purpose)) >= 10),
    CONSTRAINT ck_traffic_captures_status
        CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED', 'CANCELLED')),
    -- limits: at most 5 minutes, 100 000 packets and 100 MB
    CONSTRAINT ck_traffic_captures_limits CHECK (max_seconds BETWEEN 5 AND 300
        AND max_packets BETWEEN 100 AND 100000 AND max_bytes BETWEEN 1048576 AND 104857600),
    CONSTRAINT ck_traffic_captures_reason CHECK (failure_reason IS NULL OR failure_reason IN (
        'NO_CONSENT', 'NO_CAPTURE_TOOL', 'PERMISSION_DENIED', 'NO_INTERFACE', 'CAPTURE_ERROR', 'UNSUPPORTED_OS',
        'AGENT_NO_RESPONSE')),
    CONSTRAINT ck_traffic_captures_stop CHECK (stop_reason IS NULL OR stop_reason IN (
        'DURATION', 'PACKET_LIMIT', 'BYTE_LIMIT', 'CANCELLED')),
    CONSTRAINT ck_traffic_captures_tool CHECK (capture_tool IS NULL OR capture_tool IN (
        'NPCAP', 'PKTMON', 'RAW_SOCKET', 'PACKET_SOCKET')),
    CONSTRAINT ck_traffic_captures_analyzed CHECK (analyzed_with IS NULL OR analyzed_with IN ('AI', 'RULES')),
    -- a finished capture has its end time; only a failed one has a failure reason; only a completed one says why it
    -- stopped and has statistics
    CONSTRAINT ck_traffic_captures_finished
        CHECK ((status IN ('COMPLETED', 'FAILED', 'CANCELLED')) = (finished_at IS NOT NULL)),
    CONSTRAINT ck_traffic_captures_failed CHECK ((status = 'FAILED') = (failure_reason IS NOT NULL)),
    CONSTRAINT ck_traffic_captures_completed CHECK ((status = 'COMPLETED') = (stop_reason IS NOT NULL)
        AND (status <> 'COMPLETED' OR (packet_count IS NOT NULL AND byte_count IS NOT NULL))),
    CONSTRAINT ck_traffic_captures_order CHECK ((started_at IS NULL OR started_at >= requested_at)
        AND (finished_at IS NULL OR finished_at >= requested_at)
        AND (cancel_requested_at IS NULL OR cancel_requested_at >= requested_at)),
    -- the statistics never go over the limits the administrator set
    CONSTRAINT ck_traffic_captures_counts CHECK (
        (packet_count IS NULL OR packet_count BETWEEN 0 AND max_packets)
        AND (byte_count IS NULL OR byte_count BETWEEN 0 AND max_bytes)
        AND (duration_ms IS NULL OR duration_ms BETWEEN 0 AND (max_seconds + 60) * 1000)
        AND (dropped_by_tool IS NULL OR dropped_by_tool >= 0)
        AND (malformed_packets IS NULL OR malformed_packets >= 0)
        AND (inbound_bytes IS NULL OR inbound_bytes >= 0) AND (outbound_bytes IS NULL OR outbound_bytes >= 0)
        AND (broadcast_packets IS NULL OR broadcast_packets >= 0)
        AND (multicast_packets IS NULL OR multicast_packets >= 0)
        AND (distinct_local_hosts IS NULL OR distinct_local_hosts >= 0)
        AND (distinct_remote_hosts IS NULL OR distinct_remote_hosts >= 0)),
    CONSTRAINT ck_traffic_captures_interface CHECK (interface_name IS NULL OR length(btrim(interface_name)) > 0)
);

-- At most one capture waiting or running per network.
CREATE UNIQUE INDEX uq_traffic_captures_active ON traffic_captures (network_id)
    WHERE status IN ('PENDING', 'RUNNING');
-- History of a network, newest first.
CREATE INDEX idx_traffic_captures_network ON traffic_captures (network_id, requested_at DESC);
-- Who asked (deleting an account must not scan the whole table).
CREATE INDEX idx_traffic_captures_requested_by ON traffic_captures (requested_by);
-- Nightly retention.
CREATE INDEX idx_traffic_captures_requested_at ON traffic_captures (requested_at);

COMMENT ON TABLE traffic_captures IS
    'Capturas técnicas de tráfico en redes del equipo, pedidas por un administrador y hechas por el sensor; solo estadísticas, nunca contenido ni direcciones.';
COMMENT ON COLUMN traffic_captures.id IS 'Identificador (lo usa el sensor para entregar el resultado).';
COMMENT ON COLUMN traffic_captures.network_id IS 'Red del equipo cuyo sensor hace la captura.';
COMMENT ON COLUMN traffic_captures.requested_by IS 'Administrador que la pidió; NULL si la cuenta se borró (la auditoría conserva el nombre).';
COMMENT ON COLUMN traffic_captures.purpose IS 'Propósito autorizado que escribió el administrador (mínimo 10 caracteres).';
COMMENT ON COLUMN traffic_captures.status IS 'PENDING, RUNNING, COMPLETED, FAILED o CANCELLED (cancelada antes de empezar).';
COMMENT ON COLUMN traffic_captures.max_seconds IS 'Duración máxima (5 a 300 s).';
COMMENT ON COLUMN traffic_captures.max_packets IS 'Paquetes máximos (100 a 100 000).';
COMMENT ON COLUMN traffic_captures.max_bytes IS 'Bytes máximos (1 a 100 MB).';
COMMENT ON COLUMN traffic_captures.requested_at IS 'Cuándo se pidió.';
COMMENT ON COLUMN traffic_captures.started_at IS 'Cuándo el sensor empezó a capturar.';
COMMENT ON COLUMN traffic_captures.finished_at IS 'Cuándo terminó, falló o se canceló.';
COMMENT ON COLUMN traffic_captures.cancel_requested_at IS 'Cuándo el administrador pidió detenerla.';
COMMENT ON COLUMN traffic_captures.failure_reason IS
    'Por qué falló: NO_CONSENT, NO_CAPTURE_TOOL, PERMISSION_DENIED, NO_INTERFACE, CAPTURE_ERROR, UNSUPPORTED_OS o AGENT_NO_RESPONSE.';
COMMENT ON COLUMN traffic_captures.stop_reason IS 'Por qué se detuvo una captura completada: DURATION, PACKET_LIMIT, BYTE_LIMIT o CANCELLED.';
COMMENT ON COLUMN traffic_captures.capture_tool IS 'Herramienta usada: NPCAP, PKTMON, RAW_SOCKET (Windows) o PACKET_SOCKET (Linux).';
COMMENT ON COLUMN traffic_captures.interface_name IS 'Interfaz de red en la que capturó.';
COMMENT ON COLUMN traffic_captures.agent_version IS 'Versión del agente que capturó.';
COMMENT ON COLUMN traffic_captures.duration_ms IS 'Cuánto duró la captura en el computador del sensor.';
COMMENT ON COLUMN traffic_captures.packet_count IS 'Paquetes capturados de verdad.';
COMMENT ON COLUMN traffic_captures.byte_count IS 'Bytes de esos paquetes (su tamaño real, aunque solo se lean las cabeceras).';
COMMENT ON COLUMN traffic_captures.dropped_by_tool IS
    'Paquetes que la herramienta de captura informó como perdidos (no es la pérdida de una prueba de conexión); NULL si no lo informa.';
COMMENT ON COLUMN traffic_captures.malformed_packets IS 'Paquetes cuyas cabeceras no se pudieron leer.';
COMMENT ON COLUMN traffic_captures.inbound_bytes IS 'Bytes que llegaron al computador del sensor.';
COMMENT ON COLUMN traffic_captures.outbound_bytes IS 'Bytes que salieron del computador del sensor.';
COMMENT ON COLUMN traffic_captures.broadcast_packets IS 'Paquetes de difusión (para todos los equipos de la red).';
COMMENT ON COLUMN traffic_captures.multicast_packets IS 'Paquetes de multidifusión.';
COMMENT ON COLUMN traffic_captures.distinct_local_hosts IS 'Direcciones distintas de la red local vistas (solo el número).';
COMMENT ON COLUMN traffic_captures.distinct_remote_hosts IS 'Direcciones distintas de Internet vistas (solo el número).';
COMMENT ON COLUMN traffic_captures.analyzed_with IS 'AI si el servicio de IA analizó la captura; RULES si solo se aplicaron las reglas del backend.';
