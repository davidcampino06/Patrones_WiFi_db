-- Avance 16: recognize the devices on a network, and the AI trained with real measurements.
--
-- 1. What kind of device it is (agent_devices and network_sensor_devices). Phones hide their maker behind a private
--    MAC and many do not announce a name, so the agent (1.7.0) now also reads what devices announce on the network
--    (mDNS/Bonjour and UPnP: "iPhone de Ana", "Sala TV", the model) and which services they offer, and sends:
--      kind:  PHONE, COMPUTER, TV, PRINTER, CAMERA, SPEAKER, CONSOLE or IOT (a guess, never certain);
--      role:  SELF for the computer the agent runs on, ROUTER for the gateway of the network;
--      model: the model the device announces ("MacBookPro18,1", "Chromecast"), when it announces one.
--    As before, the MAC itself never leaves the user's computer.
--
-- 2. "Which device is this?": while identify_until is in the future, the backend asks the agent (in the answer to each
--    report) to report every minute instead of every five, so the page can tell which device disappeared when the
--    user turns its Wi-Fi off, and which one came back.
--
-- 3. ai_model_versions: each training of the anomaly model with real measurements, its metrics against the model in
--    use and whether it replaced it. The training set is kept (only the numeric features, no network or device data)
--    so the AI service can rebuild exactly the active model after a restart.
ALTER TABLE agent_devices
    ADD COLUMN kind  VARCHAR(12),
    ADD COLUMN role  VARCHAR(8),
    ADD COLUMN model VARCHAR(63),
    ADD CONSTRAINT ck_agent_devices_kind
        CHECK (kind IS NULL OR kind IN ('PHONE', 'COMPUTER', 'TV', 'PRINTER', 'CAMERA', 'SPEAKER', 'CONSOLE', 'IOT')),
    ADD CONSTRAINT ck_agent_devices_role CHECK (role IS NULL OR role IN ('SELF', 'ROUTER')),
    ADD CONSTRAINT ck_agent_devices_model CHECK (model IS NULL OR length(btrim(model)) > 0);

ALTER TABLE network_sensor_devices
    ADD COLUMN kind  VARCHAR(12),
    ADD COLUMN role  VARCHAR(8),
    ADD COLUMN model VARCHAR(63),
    ADD CONSTRAINT ck_network_sensor_devices_kind
        CHECK (kind IS NULL OR kind IN ('PHONE', 'COMPUTER', 'TV', 'PRINTER', 'CAMERA', 'SPEAKER', 'CONSOLE', 'IOT')),
    ADD CONSTRAINT ck_network_sensor_devices_role CHECK (role IS NULL OR role IN ('SELF', 'ROUTER')),
    ADD CONSTRAINT ck_network_sensor_devices_model CHECK (model IS NULL OR length(btrim(model)) > 0);

ALTER TABLE agent_keys ADD COLUMN identify_until TIMESTAMPTZ;
ALTER TABLE network_sensors ADD COLUMN identify_until TIMESTAMPTZ;

CREATE TABLE ai_model_versions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      VARCHAR(40)  NOT NULL,
    algorithm    VARCHAR(40)  NOT NULL,
    trained_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    trained_by   BIGINT,
    samples      INTEGER      NOT NULL,
    networks     INTEGER      NOT NULL,
    data_from    TIMESTAMPTZ  NOT NULL,
    data_to      TIMESTAMPTZ  NOT NULL,
    metrics      JSONB        NOT NULL DEFAULT '{}',
    decision     VARCHAR(10)  NOT NULL,
    reason       VARCHAR(300) NOT NULL,
    active       BOOLEAN      NOT NULL DEFAULT FALSE,
    training_set JSONB        NOT NULL,
    CONSTRAINT uq_ai_model_versions_version UNIQUE (version),
    CONSTRAINT fk_ai_model_versions_trained_by FOREIGN KEY (trained_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_ai_model_versions_samples CHECK (samples > 0 AND networks > 0),
    CONSTRAINT ck_ai_model_versions_period CHECK (data_to >= data_from),
    CONSTRAINT ck_ai_model_versions_decision CHECK (decision IN ('PROMOTED', 'REJECTED')),
    CONSTRAINT ck_ai_model_versions_active CHECK (NOT active OR decision = 'PROMOTED'),
    CONSTRAINT ck_ai_model_versions_metrics_object CHECK (jsonb_typeof(metrics) = 'object'),
    CONSTRAINT ck_ai_model_versions_training_set CHECK (jsonb_typeof(training_set) = 'array'),
    CONSTRAINT ck_ai_model_versions_reason CHECK (length(btrim(reason)) > 0)
);

-- At most one model in use, and the history newest first.
CREATE UNIQUE INDEX uq_ai_model_versions_active ON ai_model_versions (active) WHERE active;
CREATE INDEX idx_ai_model_versions_trained_at ON ai_model_versions (trained_at DESC);
CREATE INDEX idx_ai_model_versions_trained_by ON ai_model_versions (trained_by);

COMMENT ON COLUMN agent_devices.kind IS
    'Tipo de equipo que deduce el agente (PHONE, COMPUTER, TV, PRINTER, CAMERA, SPEAKER, CONSOLE, IOT); una suposición.';
COMMENT ON COLUMN agent_devices.role IS 'SELF: el computador del agente; ROUTER: la puerta de enlace de la red.';
COMMENT ON COLUMN agent_devices.model IS 'Modelo que el equipo anuncia en la red (mDNS o UPnP); opcional.';
COMMENT ON COLUMN network_sensor_devices.kind IS
    'Tipo de equipo que deduce el sensor (PHONE, COMPUTER, TV, PRINTER, CAMERA, SPEAKER, CONSOLE, IOT); una suposición.';
COMMENT ON COLUMN network_sensor_devices.role IS 'SELF: el computador del sensor; ROUTER: la puerta de enlace de la red.';
COMMENT ON COLUMN network_sensor_devices.model IS 'Modelo que el equipo anuncia en la red (mDNS o UPnP); opcional.';
COMMENT ON COLUMN agent_keys.identify_until IS
    'Hasta cuándo el agente reporta cada minuto para identificar un equipo (asistente de Mi Wi-Fi); NULL si no.';
COMMENT ON COLUMN network_sensors.identify_until IS
    'Hasta cuándo el sensor reporta cada minuto para identificar un equipo; NULL si no.';

COMMENT ON TABLE ai_model_versions IS
    'Cada entrenamiento del modelo de anomalías con mediciones reales, su evaluación y si reemplazó al modelo en uso.';
COMMENT ON COLUMN ai_model_versions.id IS 'Identificador.';
COMMENT ON COLUMN ai_model_versions.version IS 'Nombre de la versión del modelo (por ejemplo real-20261019-1).';
COMMENT ON COLUMN ai_model_versions.algorithm IS 'Algoritmo (IsolationForest).';
COMMENT ON COLUMN ai_model_versions.trained_at IS 'Momento del entrenamiento.';
COMMENT ON COLUMN ai_model_versions.trained_by IS 'Administrador que lo pidió; NULL si fue el entrenamiento automático semanal.';
COMMENT ON COLUMN ai_model_versions.samples IS 'Mediciones reales usadas.';
COMMENT ON COLUMN ai_model_versions.networks IS 'Redes de donde vienen esas mediciones.';
COMMENT ON COLUMN ai_model_versions.data_from IS 'Fecha de la medición más antigua usada.';
COMMENT ON COLUMN ai_model_versions.data_to IS 'Fecha de la medición más reciente usada.';
COMMENT ON COLUMN ai_model_versions.metrics IS
    'Métricas del modelo nuevo y del que estaba en uso con los mismos datos de prueba (F1, recall, falsas alarmas).';
COMMENT ON COLUMN ai_model_versions.decision IS 'PROMOTED si reemplazó al modelo en uso; REJECTED si no fue mejor.';
COMMENT ON COLUMN ai_model_versions.reason IS 'Por qué se tomó esa decisión, en palabras.';
COMMENT ON COLUMN ai_model_versions.active IS 'TRUE para el modelo que usa la IA ahora (como mucho uno).';
COMMENT ON COLUMN ai_model_versions.training_set IS
    'Las mediciones usadas, solo sus valores numéricos, para reconstruir el mismo modelo si la IA se reinicia.';
