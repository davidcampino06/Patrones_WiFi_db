-- Reports the agent sends every few minutes, with the verdicts the AI gave them. Every measurement is optional
-- (the agent reports what it could read); the AI verdicts stay NULL when the AI service was unavailable.
CREATE TABLE agent_reports (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_network_id        BIGINT           NOT NULL,
    received_at            TIMESTAMPTZ      NOT NULL DEFAULT NOW(),
    agent_version          VARCHAR(20)      NOT NULL,
    ssid                   VARCHAR(64),
    authentication         VARCHAR(10)      NOT NULL DEFAULT 'UNKNOWN',
    band                   VARCHAR(3),
    channel                SMALLINT,
    signal_dbm             SMALLINT,
    latency_ms             DOUBLE PRECISION,
    jitter_ms              DOUBLE PRECISION,
    packet_loss_pct        DOUBLE PRECISION,
    gateway_latency_ms     DOUBLE PRECISION,
    device_count           SMALLINT         NOT NULL,
    new_device_count       SMALLINT         NOT NULL DEFAULT 0,
    security_score         SMALLINT,
    security_grade         VARCHAR(10),
    quality_score          SMALLINT,
    anomaly_detected       BOOLEAN,
    anomaly_type           VARCHAR(20),
    details                JSONB            NOT NULL DEFAULT '{}',
    CONSTRAINT fk_agent_reports_network FOREIGN KEY (home_network_id) REFERENCES home_networks (id) ON DELETE CASCADE,
    CONSTRAINT ck_agent_reports_authentication CHECK (authentication IN ('OPEN', 'WEP', 'WPA', 'WPA2', 'WPA3', 'UNKNOWN')),
    CONSTRAINT ck_agent_reports_band CHECK (band IN ('2.4', '5', '6')),
    CONSTRAINT ck_agent_reports_channel CHECK (channel BETWEEN 1 AND 233),
    CONSTRAINT ck_agent_reports_signal CHECK (signal_dbm BETWEEN -100 AND 0),
    CONSTRAINT ck_agent_reports_latency CHECK (latency_ms BETWEEN 0 AND 10000 AND jitter_ms BETWEEN 0 AND 10000
                                               AND gateway_latency_ms BETWEEN 0 AND 10000),
    CONSTRAINT ck_agent_reports_loss CHECK (packet_loss_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_agent_reports_devices CHECK (device_count BETWEEN 0 AND 1024
                                               AND new_device_count BETWEEN 0 AND device_count),
    CONSTRAINT ck_agent_reports_security CHECK (security_score BETWEEN 0 AND 100
                                                AND security_grade IN ('SECURE', 'ACCEPTABLE', 'AT_RISK', 'CRITICAL')),
    CONSTRAINT ck_agent_reports_security_complete CHECK ((security_score IS NULL) = (security_grade IS NULL)),
    CONSTRAINT ck_agent_reports_quality CHECK (quality_score BETWEEN 0 AND 100),
    CONSTRAINT ck_agent_reports_anomaly_type CHECK (anomaly_type IN (
        'NONE', 'CONGESTION', 'INTERFERENCE', 'WEAK_COVERAGE', 'PROVIDER_ISSUE', 'SUSPICIOUS_TRAFFIC', 'UNKNOWN')),
    CONSTRAINT ck_agent_reports_anomaly_matches CHECK (
        anomaly_type IS NULL OR (anomaly_detected IS NOT NULL AND anomaly_detected = (anomaly_type <> 'NONE')))
);

-- Latest reports of a network (Mi Wi-Fi) and the window the AI analyses.
CREATE INDEX idx_agent_reports_network_time ON agent_reports (home_network_id, received_at DESC);
-- Daily deletion of reports older than the retention period.
CREATE INDEX idx_agent_reports_received ON agent_reports (received_at);
