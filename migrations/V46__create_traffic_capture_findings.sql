-- Avance 24: what the analysis of a capture concluded, keeping apart what was measured from what was inferred.
--   OBSERVED  a fact computed from the captured packets ("80 % of the packets were broadcast", "the capture tool
--             reported 120 dropped packets"); no confidence, it is a count;
--   INFERRED  a possible explanation drawn by the AI or the rules ("a burst of traffic at second 14 that does not
--             match the rest"), always with its confidence (0 to 1) and the evidence it rests on.
-- A finding never claims that a device is malicious: at most it says what deserves a look, and how to check it.
CREATE TABLE traffic_capture_findings (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capture_id     BIGINT       NOT NULL REFERENCES traffic_captures (id) ON DELETE CASCADE,
    category       VARCHAR(8)   NOT NULL,
    code           VARCHAR(32)  NOT NULL,
    severity       VARCHAR(8)   NOT NULL,
    title          VARCHAR(120) NOT NULL,
    evidence       VARCHAR(400) NOT NULL,
    recommendation VARCHAR(400),
    confidence     NUMERIC(3, 2),
    source         VARCHAR(6)   NOT NULL,
    CONSTRAINT ck_traffic_capture_findings_category CHECK (category IN ('OBSERVED', 'INFERRED')),
    CONSTRAINT ck_traffic_capture_findings_severity CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL')),
    CONSTRAINT ck_traffic_capture_findings_source CHECK (source IN ('AI', 'RULES')),
    CONSTRAINT ck_traffic_capture_findings_code CHECK (code ~ '^[A-Z][A-Z0-9_]{2,31}$')
);

CREATE INDEX idx_traffic_capture_findings_capture ON traffic_capture_findings (capture_id);

COMMENT ON TABLE traffic_capture_findings IS
    'Conclusiones del análisis de una captura: hechos observados y posibles explicaciones inferidas, con su evidencia.';
COMMENT ON COLUMN traffic_capture_findings.id IS 'Identificador.';
COMMENT ON COLUMN traffic_capture_findings.capture_id IS 'Captura analizada.';
COMMENT ON COLUMN traffic_capture_findings.category IS 'OBSERVED (un hecho medido) o INFERRED (una explicación posible, con confianza).';
COMMENT ON COLUMN traffic_capture_findings.code IS 'Código estable del hallazgo (por ejemplo BROADCAST_SHARE o TRAFFIC_BURST).';
COMMENT ON COLUMN traffic_capture_findings.severity IS 'INFO, WARNING o CRITICAL.';
COMMENT ON COLUMN traffic_capture_findings.title IS 'Título corto para la página.';
COMMENT ON COLUMN traffic_capture_findings.evidence IS 'Los números en los que se apoya.';
COMMENT ON COLUMN traffic_capture_findings.recommendation IS 'Acción defensiva y verificable sugerida; opcional.';
COMMENT ON COLUMN traffic_capture_findings.confidence IS 'Confianza de una inferencia entre 0 y 1; NULL en una observación.';
COMMENT ON COLUMN traffic_capture_findings.source IS 'AI (servicio de IA) o RULES (reglas del backend cuando la IA no estaba disponible).';
