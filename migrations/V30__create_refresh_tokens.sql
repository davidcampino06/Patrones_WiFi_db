-- Avance 11: refresh tokens, so a session renews itself without asking for the password again.
-- The access token (JWT) lives a few minutes; when it expires the browser presents its refresh token and receives a new
-- pair. Only the SHA-256 of the refresh token is stored, so a copy of the database cannot open anyone's session.
-- Rotation: each refresh token works once and is replaced by a new one of the same family (one family per login).
-- If an already used token is presented again, someone copied it, and the backend revokes the whole family.
CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL,
    family_id   UUID        NOT NULL,
    token_hash  CHAR(64)    NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at  TIMESTAMPTZ NOT NULL,
    used_at     TIMESTAMPTZ,
    revoked_at  TIMESTAMPTZ,
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_tokens_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_refresh_tokens_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_refresh_tokens_used CHECK (used_at IS NULL OR used_at >= created_at),
    CONSTRAINT ck_refresh_tokens_revoked CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);

-- Sessions of a user (to close them all when the password changes), the tokens of one family (to revoke it after a
-- reuse) and the nightly cleanup of expired ones.
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_expires_at ON refresh_tokens (expires_at);
