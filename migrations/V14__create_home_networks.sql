-- Networks that end users register for themselves. They live apart from the university networks the team
-- monitors, so the monitoring job and the team views never touch them, and each row belongs to one user.
CREATE TABLE home_networks (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id         BIGINT      NOT NULL,
    name             VARCHAR(40) NOT NULL,
    provider         VARCHAR(60),
    contracted_mbps  INTEGER,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_home_networks_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_home_networks_name CHECK (char_length(btrim(name)) BETWEEN 2 AND 40),
    CONSTRAINT ck_home_networks_contracted CHECK (contracted_mbps BETWEEN 1 AND 10000)
);

-- One name per owner (case-insensitive); also serves the "networks of this user" lookup.
CREATE UNIQUE INDEX uq_home_networks_owner_name ON home_networks (owner_id, lower(name));
