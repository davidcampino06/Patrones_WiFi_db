-- Avance 24: each access point (BSSID) a network's agent has seen around it, kept once no matter how many scans saw
-- it, so repeating a scan does not pile up copies: the scan only moves last_seen_at and adds one to times_seen.
--
-- Like the devices of the network (agent_devices), the BSSID itself never leaves the agent's computer: the agent
-- sends a SHA-256 fingerprint with its own salt (24 hex characters) and, to help the user recognize their own router
-- on its sticker, only the last byte of the BSSID (for example "F1"). The maker comes from the OUI (the first three
-- bytes) and is a guess: it is unknown when the BSSID is locally administered.
CREATE TABLE wifi_access_points (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_network_id   BIGINT      NOT NULL REFERENCES home_networks (id) ON DELETE CASCADE,
    bssid_fingerprint CHAR(24)    NOT NULL,
    bssid_suffix      CHAR(2),
    vendor            VARCHAR(60),
    ssid              VARCHAR(64),
    hidden            BOOLEAN     NOT NULL DEFAULT FALSE,
    first_seen_at     TIMESTAMPTZ NOT NULL,
    last_seen_at      TIMESTAMPTZ NOT NULL,
    times_seen        INTEGER     NOT NULL DEFAULT 1,
    CONSTRAINT uq_wifi_access_points_bssid UNIQUE (home_network_id, bssid_fingerprint),
    CONSTRAINT ck_wifi_access_points_fingerprint CHECK (bssid_fingerprint ~ '^[0-9a-f]{24}$'),
    CONSTRAINT ck_wifi_access_points_suffix CHECK (bssid_suffix IS NULL OR bssid_suffix ~ '^[0-9A-F]{2}$'),
    -- a hidden network does not say its name; a visible one always has one
    CONSTRAINT ck_wifi_access_points_hidden CHECK (hidden = (ssid IS NULL)),
    CONSTRAINT ck_wifi_access_points_ssid CHECK (ssid IS NULL OR length(ssid) > 0),
    CONSTRAINT ck_wifi_access_points_vendor CHECK (vendor IS NULL OR length(btrim(vendor)) > 0),
    CONSTRAINT ck_wifi_access_points_seen CHECK (last_seen_at >= first_seen_at),
    CONSTRAINT ck_wifi_access_points_times CHECK (times_seen >= 1)
);

-- Access points of a network, most recently seen first; and the cleanup of those not seen for months.
CREATE INDEX idx_wifi_access_points_network ON wifi_access_points (home_network_id, last_seen_at DESC);
CREATE INDEX idx_wifi_access_points_last_seen ON wifi_access_points (last_seen_at);

COMMENT ON TABLE wifi_access_points IS
    'Puntos de acceso (BSSID) que el agente de cada red de Mi Wi-Fi vio alrededor; uno por BSSID, sin copias por escaneo.';
COMMENT ON COLUMN wifi_access_points.id IS 'Identificador del punto de acceso.';
COMMENT ON COLUMN wifi_access_points.home_network_id IS 'Red de Mi Wi-Fi cuyo agente lo vio.';
COMMENT ON COLUMN wifi_access_points.bssid_fingerprint IS 'Huella SHA-256 con sal del BSSID (24 hex); nunca el BSSID completo.';
COMMENT ON COLUMN wifi_access_points.bssid_suffix IS 'Último byte del BSSID (por ejemplo F1) para reconocer el propio router; NULL si no se envió.';
COMMENT ON COLUMN wifi_access_points.vendor IS 'Fabricante estimado por el OUI del BSSID; NULL si no se conoce.';
COMMENT ON COLUMN wifi_access_points.ssid IS 'Nombre de la red la última vez que se vio; NULL si es una red oculta.';
COMMENT ON COLUMN wifi_access_points.hidden IS 'TRUE si la red no anuncia su nombre.';
COMMENT ON COLUMN wifi_access_points.first_seen_at IS 'Primer escaneo que lo vio.';
COMMENT ON COLUMN wifi_access_points.last_seen_at IS 'Último escaneo que lo vio.';
COMMENT ON COLUMN wifi_access_points.times_seen IS 'En cuántos escaneos completados apareció.';
