-- Short codes to install the agent without copying the long key. Mi Wi-Fi shows the code (8 characters, valid for
-- 15 minutes); the installer sends it once and receives the agent key. Only the SHA-256 of the code is stored, a
-- network has at most one pending code, and a used code never works again.
CREATE TABLE agent_pairing_codes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_network_id  BIGINT      NOT NULL,
    code_hash        CHAR(64)    NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at       TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_agent_pairing_codes_network FOREIGN KEY (home_network_id) REFERENCES home_networks (id) ON DELETE CASCADE,
    CONSTRAINT uq_agent_pairing_codes_network UNIQUE (home_network_id),
    CONSTRAINT uq_agent_pairing_codes_hash UNIQUE (code_hash),
    CONSTRAINT ck_agent_pairing_codes_hash CHECK (code_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_agent_pairing_codes_expiry CHECK (expires_at > created_at AND expires_at <= created_at + INTERVAL '1 hour')
);
