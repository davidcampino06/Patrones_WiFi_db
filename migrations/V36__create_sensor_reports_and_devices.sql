-- Avance 14: the team networks get what Mi Wi-Fi already shows. The sensor of a team network is the same agent, and
-- every report already carries the devices it sees, the router's open ports and the neighbour networks per channel;
-- until now the backend only kept the measurement. These two tables keep the rest, like agent_reports and
-- agent_devices do for the home networks:
--
-- network_sensor_reports: each report with the AI verdicts (security audit, quality and best channel in details).
-- network_sensor_devices: the devices seen on the network. As in Mi Wi-Fi, the agent never sends a MAC address, only a
--   salted SHA-256 fingerprint (24 hex characters), the maker read from the first bytes of the MAC, the name the
--   device announces and whether it uses a private (random) address. An administrator can name a device and mark it
--   as not authorized.
--
-- Both are deleted with their network, and the nightly cleanup removes what is older than 30 days, as for Mi Wi-Fi.
CREATE TABLE network_sensor_reports (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_id         BIGINT           NOT NULL,
    received_at        TIMESTAMPTZ      NOT NULL DEFAULT NOW(),
    agent_version      VARCHAR(20)      NOT NULL,
    ssid               VARCHAR(64),
    authentication     VARCHAR(10)      NOT NULL DEFAULT 'UNKNOWN',
    band               VARCHAR(3),
    channel            SMALLINT,
    signal_dbm         SMALLINT,
    latency_ms         DOUBLE PRECISION,
    jitter_ms          DOUBLE PRECISION,
    packet_loss_pct    DOUBLE PRECISION,
    gateway_latency_ms DOUBLE PRECISION,
    device_count       SMALLINT         NOT NULL,
    new_device_count   SMALLINT         NOT NULL DEFAULT 0,
    security_score     SMALLINT,
    security_grade     VARCHAR(10),
    quality_score      SMALLINT,
    details            JSONB            NOT NULL DEFAULT '{}',
    CONSTRAINT fk_network_sensor_reports_network FOREIGN KEY (network_id) REFERENCES networks (id) ON DELETE CASCADE,
    CONSTRAINT ck_network_sensor_reports_authentication
        CHECK (authentication IN ('OPEN', 'WEP', 'WPA', 'WPA2', 'WPA3', 'UNKNOWN')),
    CONSTRAINT ck_network_sensor_reports_band CHECK (band IN ('2.4', '5', '6')),
    CONSTRAINT ck_network_sensor_reports_channel CHECK (channel BETWEEN 1 AND 233),
    CONSTRAINT ck_network_sensor_reports_signal CHECK (signal_dbm BETWEEN -100 AND 0),
    CONSTRAINT ck_network_sensor_reports_latency CHECK (latency_ms BETWEEN 0 AND 10000 AND jitter_ms BETWEEN 0 AND 10000
                                                        AND gateway_latency_ms BETWEEN 0 AND 10000),
    CONSTRAINT ck_network_sensor_reports_loss CHECK (packet_loss_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_network_sensor_reports_devices CHECK (device_count BETWEEN 0 AND 1024
                                                        AND new_device_count BETWEEN 0 AND device_count),
    CONSTRAINT ck_network_sensor_reports_security CHECK (security_score BETWEEN 0 AND 100
        AND security_grade IN ('SECURE', 'ACCEPTABLE', 'AT_RISK', 'CRITICAL')),
    CONSTRAINT ck_network_sensor_reports_security_complete CHECK ((security_score IS NULL) = (security_grade IS NULL)),
    CONSTRAINT ck_network_sensor_reports_quality CHECK (quality_score BETWEEN 0 AND 100),
    CONSTRAINT ck_network_sensor_reports_details_object CHECK (jsonb_typeof(details) = 'object')
);

-- Latest reports of a team network (the sensor panel) and the nightly cleanup by date.
CREATE INDEX idx_network_sensor_reports_network_time ON network_sensor_reports (network_id, received_at DESC);
CREATE INDEX idx_network_sensor_reports_received ON network_sensor_reports (received_at);

CREATE TABLE network_sensor_devices (
    network_id    BIGINT      NOT NULL,
    fingerprint   CHAR(24)    NOT NULL,
    label         VARCHAR(40),
    vendor        VARCHAR(40),
    hostname      VARCHAR(63),
    authorized    BOOLEAN     NOT NULL DEFAULT TRUE,
    private_mac   BOOLEAN     NOT NULL DEFAULT FALSE,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (network_id, fingerprint),
    CONSTRAINT fk_network_sensor_devices_network FOREIGN KEY (network_id) REFERENCES networks (id) ON DELETE CASCADE,
    CONSTRAINT ck_network_sensor_devices_fingerprint CHECK (fingerprint ~ '^[0-9a-f]{24}$'),
    CONSTRAINT ck_network_sensor_devices_label CHECK (label IS NULL OR length(btrim(label)) > 0),
    CONSTRAINT ck_network_sensor_devices_vendor CHECK (vendor IS NULL OR length(btrim(vendor)) > 0),
    CONSTRAINT ck_network_sensor_devices_hostname CHECK (hostname IS NULL OR length(btrim(hostname)) > 0),
    CONSTRAINT ck_network_sensor_devices_seen CHECK (last_seen_at >= first_seen_at)
);

-- Nightly cleanup of devices not seen for 30 days (the primary key already indexes the network).
CREATE INDEX idx_network_sensor_devices_last_seen ON network_sensor_devices (last_seen_at);

