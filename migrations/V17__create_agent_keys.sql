-- Key of the WiFiSense agent that runs in the user's home. One key per home network: creating a new one replaces
-- the old one. Only the SHA-256 of the key is stored; the key itself is shown once to the user and never again.
CREATE TABLE agent_keys (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_network_id  BIGINT      NOT NULL,
    key_hash         CHAR(64)    NOT NULL,
    key_prefix       VARCHAR(12) NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at     TIMESTAMPTZ,
    CONSTRAINT fk_agent_keys_network FOREIGN KEY (home_network_id) REFERENCES home_networks (id) ON DELETE CASCADE,
    CONSTRAINT uq_agent_keys_network UNIQUE (home_network_id),
    CONSTRAINT uq_agent_keys_hash UNIQUE (key_hash),
    CONSTRAINT ck_agent_keys_hash CHECK (key_hash ~ '^[0-9a-f]{64}$'),
    -- The visible start of the key, so the user can tell which key the agent has ("wsa_AbC1...").
    CONSTRAINT ck_agent_keys_prefix CHECK (key_prefix ~ '^wsa_[A-Za-z0-9_-]{4,8}$')
);
