-- Avance 15: when each device was connected. Until now a device only had the first and the last time it was seen;
-- these tables keep each period it stayed connected ("from 2:10 p. m. to 3:05 p. m."), for the devices of Mi Wi-Fi
-- (agent_devices) and for those the sensor of a team network sees (network_sensor_devices).
--
-- The agent reports every 5 minutes, so a period starts with the first report that sees the device and grows with
-- every report that sees it again (last_seen_at). A phone at rest sometimes does not answer for a few minutes while
-- still connected, so a period is closed only when the device has been missing for a while (the backend waits about
-- two reports): then disconnected_at is the last time it was seen. An open period has disconnected_at NULL, and a
-- device has at most one open period. Like the devices, nothing here says which device it is: only its fingerprint.
CREATE TABLE agent_device_sessions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_network_id BIGINT      NOT NULL,
    fingerprint     CHAR(24)    NOT NULL,
    connected_at    TIMESTAMPTZ NOT NULL,
    last_seen_at    TIMESTAMPTZ NOT NULL,
    disconnected_at TIMESTAMPTZ,
    CONSTRAINT fk_agent_device_sessions_device FOREIGN KEY (home_network_id, fingerprint)
        REFERENCES agent_devices (home_network_id, fingerprint) ON DELETE CASCADE,
    CONSTRAINT ck_agent_device_sessions_seen CHECK (last_seen_at >= connected_at),
    CONSTRAINT ck_agent_device_sessions_end CHECK (disconnected_at IS NULL OR disconnected_at >= last_seen_at)
);

-- One open period per device, and the history of a device (newest first).
CREATE UNIQUE INDEX uq_agent_device_sessions_open ON agent_device_sessions (home_network_id, fingerprint)
    WHERE disconnected_at IS NULL;
CREATE INDEX idx_agent_device_sessions_device ON agent_device_sessions (home_network_id, fingerprint, connected_at DESC);
-- Nightly cleanup of old periods.
CREATE INDEX idx_agent_device_sessions_last_seen ON agent_device_sessions (last_seen_at);

CREATE TABLE network_sensor_device_sessions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_id      BIGINT      NOT NULL,
    fingerprint     CHAR(24)    NOT NULL,
    connected_at    TIMESTAMPTZ NOT NULL,
    last_seen_at    TIMESTAMPTZ NOT NULL,
    disconnected_at TIMESTAMPTZ,
    CONSTRAINT fk_network_sensor_device_sessions_device FOREIGN KEY (network_id, fingerprint)
        REFERENCES network_sensor_devices (network_id, fingerprint) ON DELETE CASCADE,
    CONSTRAINT ck_network_sensor_device_sessions_seen CHECK (last_seen_at >= connected_at),
    CONSTRAINT ck_network_sensor_device_sessions_end
        CHECK (disconnected_at IS NULL OR disconnected_at >= last_seen_at)
);

CREATE UNIQUE INDEX uq_network_sensor_device_sessions_open ON network_sensor_device_sessions (network_id, fingerprint)
    WHERE disconnected_at IS NULL;
CREATE INDEX idx_network_sensor_device_sessions_device
    ON network_sensor_device_sessions (network_id, fingerprint, connected_at DESC);
CREATE INDEX idx_network_sensor_device_sessions_last_seen ON network_sensor_device_sessions (last_seen_at);

-- The Wi-Fi the sensor's computer was connected to in its last report. If it is not the network the sensor measures
-- (the computer moved to another Wi-Fi), the reports are not stored as that network's, and the panel says why.
ALTER TABLE network_sensors ADD COLUMN last_ssid VARCHAR(64);
COMMENT ON COLUMN network_sensors.last_ssid IS
    'Wi-Fi al que estaba conectado el computador del sensor en su último reporte; NULL si no se pudo leer (cable o permiso).';

