COMMENT ON COLUMN network_sensor_device_sessions.fingerprint IS 'Huella del equipo (la misma de network_sensor_devices; nunca la MAC).';
COMMENT ON COLUMN network_sensor_device_sessions.connected_at IS 'Primer reporte del sensor que vio al equipo en este periodo.';
COMMENT ON COLUMN network_sensor_device_sessions.last_seen_at IS 'Último reporte que lo vio en este periodo.';
