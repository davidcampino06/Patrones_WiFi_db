-- Avance 24: audit of the sensitive operations, for the administrators to review.
--
-- One row per operation: who did it (the username is copied, so the row still says who it was after the account
-- is deleted), what (action), on what (target), with which result (SUCCESS, DENIED when the backend refused it for
-- lack of permission, FAILED when it could not be done) and a short detail without secrets: never a password, a key,
-- a token, a MAC or an address.
--
-- The rows cannot be changed: an UPDATE is rejected (the only exception is the database itself emptying actor_id when
-- the account is deleted; the copied username stays), and a DELETE only removes rows older than 30 days (the nightly
-- retention), so nobody can erase a recent trace, not even the application.
CREATE TABLE audit_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    actor_id       BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    actor_username VARCHAR(100),
    actor_role     VARCHAR(8),
    action         VARCHAR(32)  NOT NULL,
    outcome        VARCHAR(8)   NOT NULL,
    target_type    VARCHAR(20),
    target_id      BIGINT,
    network_id     BIGINT,
    detail         VARCHAR(300)
);
CREATE INDEX idx_audit_events_actor ON audit_events (actor_id);

COMMENT ON TABLE audit_events IS
    'Auditoría de las operaciones sensibles (capturas, cuentas, roles, bloqueos, claves): quién, qué, sobre qué y con qué resultado. No se puede modificar.';
COMMENT ON COLUMN audit_events.id IS 'Identificador.';
COMMENT ON COLUMN audit_events.occurred_at IS 'Cuándo ocurrió.';
COMMENT ON COLUMN audit_events.actor_id IS 'Cuenta que hizo la operación; NULL si la hizo el sistema o si la cuenta se borró.';
COMMENT ON COLUMN audit_events.actor_username IS 'Usuario de esa cuenta en ese momento (se conserva aunque la cuenta se borre).';
COMMENT ON COLUMN audit_events.actor_role IS 'Rol de la cuenta en ese momento, o SYSTEM para las tareas automáticas.';
COMMENT ON COLUMN audit_events.action IS
    'Operación: CAPTURE_REQUESTED, CAPTURE_CANCELLED, CAPTURE_VIEWED, USER_CREATED, USER_ROLE_CHANGED, USER_DELETED, DEVICE_BLOCKED, DEVICE_UNBLOCKED, SENSOR_PAIRING_CREATED, AGENT_KEY_REVOKED, RETENTION_PURGED...';
COMMENT ON COLUMN audit_events.outcome IS 'SUCCESS, DENIED (sin permiso) o FAILED (no se pudo hacer).';
COMMENT ON COLUMN audit_events.target_type IS 'Tipo de lo afectado (CAPTURE, USER, DEVICE, NETWORK, HOME_NETWORK...).';
COMMENT ON COLUMN audit_events.target_id IS 'Identificador de lo afectado.';
COMMENT ON COLUMN audit_events.network_id IS 'Red relacionada, si hay una (sin llave foránea: el registro sobrevive a la red).';
COMMENT ON COLUMN audit_events.detail IS 'Detalle corto sin secretos (nunca contraseñas, claves, tokens, MAC ni direcciones).';
