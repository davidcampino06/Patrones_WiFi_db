-- Email alerts for the end user: a new device on the network, security that dropped to critical, or an anomaly.
-- The agent reports every 5 minutes; without a record of what was already sent, the same problem would email the
-- user every 5 minutes. agent_alerts both keeps a short history (shown in Mi Wi-Fi) and prevents repeated emails.
CREATE TABLE alert_preferences (
    user_id          BIGINT  PRIMARY KEY,
    email_new_device BOOLEAN NOT NULL DEFAULT TRUE,
    email_security   BOOLEAN NOT NULL DEFAULT TRUE,
    email_anomaly    BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_alert_preferences_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE agent_alerts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_network_id  BIGINT      NOT NULL,
    type             VARCHAR(20) NOT NULL,
    detail           VARCHAR(300) NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    emailed          BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_agent_alerts_network FOREIGN KEY (home_network_id) REFERENCES home_networks (id) ON DELETE CASCADE,
    CONSTRAINT ck_agent_alerts_type CHECK (type IN ('NEW_DEVICE', 'UNAUTHORIZED_DEVICE', 'SECURITY', 'ANOMALY'))
);

-- Latest alerts of a network (Mi Wi-Fi) and the dedupe check "was this type sent recently".
CREATE INDEX idx_agent_alerts_network_time ON agent_alerts (home_network_id, type, created_at DESC);
