-- Avance 24: scans of the nearby Wi-Fi networks, as the antenna of the agent's computer sees them.
--
-- A scan is a task with a life: the page (MANUAL) or the backend's own schedule (SCHEDULED) creates it as PENDING;
-- it becomes RUNNING when the agent picks it up; it ends COMPLETED (with the networks it saw, possibly none) or
-- FAILED with the reason (no Wi-Fi adapter, adapter off, the WLAN service stopped, Windows location permission, the
-- command failed or took too long, or the agent never answered). A network has at most one scan waiting or running,
-- so pressing the button twice does not queue two scans.
--
-- Seeing a network in a scan does not mean it belongs to the user, nor that the user may join or manage it: these
-- rows only describe what the adapter could see at that moment. No Wi-Fi password is ever sent or stored.
CREATE TABLE wifi_scan_sessions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_network_id    BIGINT      NOT NULL REFERENCES home_networks (id) ON DELETE CASCADE,
    origin             VARCHAR(10) NOT NULL,
    status             VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    requested_by       BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    requested_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at         TIMESTAMPTZ,
    finished_at        TIMESTAMPTZ,
    failure_reason     VARCHAR(24),
    interface_name     VARCHAR(64),
    scan_tool          VARCHAR(8),
    fresh              BOOLEAN,
    network_count      INTEGER,
    access_point_count INTEGER,
    duration_ms        INTEGER,
    agent_version      VARCHAR(20),
    CONSTRAINT ck_wifi_scan_sessions_origin CHECK (origin IN ('MANUAL', 'SCHEDULED')),
    CONSTRAINT ck_wifi_scan_sessions_status CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_wifi_scan_sessions_reason CHECK (failure_reason IS NULL OR failure_reason IN (
        'NO_ADAPTER', 'ADAPTER_OFF', 'SERVICE_OFF', 'LOCATION_PERMISSION', 'COMMAND_FAILED', 'TIMEOUT',
        'UNREADABLE_OUTPUT', 'UNSUPPORTED_OS', 'AGENT_NO_RESPONSE')),
    CONSTRAINT ck_wifi_scan_sessions_tool CHECK (scan_tool IS NULL OR scan_tool IN ('NETSH', 'NMCLI'))
);
-- History of a network, newest first (the page and the schedule read it).
CREATE INDEX idx_wifi_scan_sessions_network ON wifi_scan_sessions (home_network_id, requested_at DESC);
-- Who asked for a scan (deleting an account must not scan the whole table).
CREATE INDEX idx_wifi_scan_sessions_requested_by ON wifi_scan_sessions (requested_by);

COMMENT ON TABLE wifi_scan_sessions IS
    'Escaneos de redes Wi-Fi cercanas pedidos desde Mi Wi-Fi o programados, con su estado y por qué fallaron.';
COMMENT ON COLUMN wifi_scan_sessions.id IS 'Identificador del escaneo (lo usa el agente para entregar el resultado).';
COMMENT ON COLUMN wifi_scan_sessions.home_network_id IS 'Red de Mi Wi-Fi cuyo agente hace el escaneo.';
COMMENT ON COLUMN wifi_scan_sessions.origin IS 'MANUAL (botón Escanear ahora) o SCHEDULED (programado por el servidor).';
COMMENT ON COLUMN wifi_scan_sessions.status IS 'PENDING, RUNNING (el agente lo recibió), COMPLETED o FAILED.';
COMMENT ON COLUMN wifi_scan_sessions.requested_by IS 'Cuenta que pidió el escaneo manual; NULL si es programado o si la cuenta se borró.';
COMMENT ON COLUMN wifi_scan_sessions.requested_at IS 'Cuándo se pidió.';
COMMENT ON COLUMN wifi_scan_sessions.started_at IS 'Cuándo el agente lo recibió y empezó a escanear.';
COMMENT ON COLUMN wifi_scan_sessions.finished_at IS 'Cuándo terminó (bien o con error).';
COMMENT ON COLUMN wifi_scan_sessions.failure_reason IS
    'Por qué falló: NO_ADAPTER, ADAPTER_OFF, SERVICE_OFF, LOCATION_PERMISSION, COMMAND_FAILED, TIMEOUT, UNREADABLE_OUTPUT, UNSUPPORTED_OS o AGENT_NO_RESPONSE.';
COMMENT ON COLUMN wifi_scan_sessions.interface_name IS 'Adaptador Wi-Fi con el que se escaneó (por ejemplo "Wi-Fi").';
COMMENT ON COLUMN wifi_scan_sessions.scan_tool IS 'Herramienta del sistema: NETSH (Windows) o NMCLI (Linux).';
COMMENT ON COLUMN wifi_scan_sessions.fresh IS
    'TRUE si el agente pidió al sistema un escaneo nuevo antes de leer; FALSE si leyó la última lista que tenía el sistema.';
COMMENT ON COLUMN wifi_scan_sessions.network_count IS 'Redes distintas (SSID) que vio; 0 es un resultado válido.';
COMMENT ON COLUMN wifi_scan_sessions.access_point_count IS 'Puntos de acceso (BSSID) que vio.';
COMMENT ON COLUMN wifi_scan_sessions.duration_ms IS 'Cuánto tardó el escaneo en el computador del agente.';
COMMENT ON COLUMN wifi_scan_sessions.agent_version IS 'Versión del agente que escaneó.';
