-- Avance 24: what one scan saw of one access point: signal, channel, band, radio and the security it announces. A
-- scan sees each access point at most once. Every field the system did not report stays NULL: the agent never
-- fills a gap with a guess (for example Windows 10 gives the signal only as a percentage, so signal_dbm is NULL).
CREATE TABLE wifi_scan_observations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id         BIGINT      NOT NULL REFERENCES wifi_scan_sessions (id) ON DELETE CASCADE,
    access_point_id BIGINT      NOT NULL REFERENCES wifi_access_points (id) ON DELETE CASCADE,
    ssid            VARCHAR(64),
    signal_percent  SMALLINT,
    signal_dbm      SMALLINT,
    channel         SMALLINT,
    band            VARCHAR(4),
    radio_type      VARCHAR(20),
    authentication  VARCHAR(10) NOT NULL DEFAULT 'UNKNOWN',
    security_label  VARCHAR(40),
    cipher          VARCHAR(20),
    connected       BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_wifi_scan_observations_scan UNIQUE (scan_id, access_point_id),
    CONSTRAINT ck_wifi_scan_observations_signal CHECK (signal_percent IS NULL OR signal_percent BETWEEN 0 AND 100),
    CONSTRAINT ck_wifi_scan_observations_dbm CHECK (signal_dbm IS NULL OR signal_dbm BETWEEN -120 AND 0),
    CONSTRAINT ck_wifi_scan_observations_channel CHECK (channel IS NULL OR channel BETWEEN 1 AND 233),
    CONSTRAINT ck_wifi_scan_observations_band CHECK (band IS NULL OR band IN ('2.4', '5', '6'))
);

-- Every scan in which an access point appeared (its history).
CREATE INDEX idx_wifi_scan_observations_access_point ON wifi_scan_observations (access_point_id);

COMMENT ON TABLE wifi_scan_observations IS
    'Lo que vio cada escaneo de cada punto de acceso: señal, canal, banda, radio y seguridad anunciada.';
COMMENT ON COLUMN wifi_scan_observations.id IS 'Identificador de la observación.';
COMMENT ON COLUMN wifi_scan_observations.scan_id IS 'Escaneo que hizo la observación.';
COMMENT ON COLUMN wifi_scan_observations.access_point_id IS 'Punto de acceso observado.';
COMMENT ON COLUMN wifi_scan_observations.ssid IS 'Nombre de la red en ese escaneo; NULL si es oculta.';
COMMENT ON COLUMN wifi_scan_observations.signal_percent IS 'Calidad de la señal que da el sistema (0 a 100 %); NULL si no la dio.';
COMMENT ON COLUMN wifi_scan_observations.signal_dbm IS 'Señal en dBm solo si el sistema la dio (RSSI); nunca calculada.';
COMMENT ON COLUMN wifi_scan_observations.channel IS 'Canal Wi-Fi; NULL si no se conoce.';
COMMENT ON COLUMN wifi_scan_observations.band IS 'Banda: 2.4, 5 o 6 GHz; NULL si no se conoce.';
COMMENT ON COLUMN wifi_scan_observations.radio_type IS 'Tipo de radio anunciado (por ejemplo 802.11ax).';
COMMENT ON COLUMN wifi_scan_observations.authentication IS 'Seguridad resumida: OPEN, WEP, WPA, WPA2, WPA3 o UNKNOWN.';
COMMENT ON COLUMN wifi_scan_observations.security_label IS 'Autenticación tal como la anuncia la red (por ejemplo WPA2-Personal).';
COMMENT ON COLUMN wifi_scan_observations.cipher IS 'Cifrado anunciado (CCMP, TKIP, GCMP...).';
COMMENT ON COLUMN wifi_scan_observations.connected IS 'TRUE si es el punto de acceso al que estaba conectado el computador del agente.';
