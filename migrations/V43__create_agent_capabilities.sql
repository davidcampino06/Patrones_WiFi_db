-- Avance 24: what the computer of each agent can do, as the agent itself checks it in every report (2.0.0).
--
-- One row per agent: the agent of a Mi Wi-Fi network (home_network_id) or the sensor of a team network (network_id),
-- never both. The backend uses it to explain, before asking for anything, why a technical capture is or is not
-- possible on that computer, instead of finding out with a failed capture:
--   * capture_consent: the person who manages that computer allowed technical captures on it (agent command
--     "capture-consent on"); without it the agent refuses every capture, whatever the server asks;
--   * the capture tools it found: Npcap (driver installed by the user, for example with Wireshark), pktmon (part of
--     Windows 10/11, needs administrator), raw sockets (administrator) or packet sockets on Linux (root);
--   * whether the agent runs as administrator, and whether the Wi-Fi adapter declares monitor mode.
-- Nothing here is a secret: no keys, no addresses, no MAC.
CREATE TABLE agent_capabilities (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_network_id     BIGINT      REFERENCES home_networks (id) ON DELETE CASCADE,
    network_id          BIGINT      REFERENCES networks (id) ON DELETE CASCADE,
    platform            VARCHAR(20),
    agent_version       VARCHAR(20),
    elevated            BOOLEAN     NOT NULL DEFAULT FALSE,
    capture_consent     BOOLEAN     NOT NULL DEFAULT FALSE,
    npcap               BOOLEAN     NOT NULL DEFAULT FALSE,
    pktmon              BOOLEAN     NOT NULL DEFAULT FALSE,
    raw_socket          BOOLEAN     NOT NULL DEFAULT FALSE,
    packet_socket       BOOLEAN     NOT NULL DEFAULT FALSE,
    monitor_mode        VARCHAR(12) NOT NULL DEFAULT 'UNKNOWN',
    capture_interfaces  SMALLINT    NOT NULL DEFAULT 0,
    reported_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- exactly one owner: a Mi Wi-Fi network or a team network
    CONSTRAINT uq_agent_capabilities_home UNIQUE (home_network_id),
    CONSTRAINT uq_agent_capabilities_network UNIQUE (network_id)
);

COMMENT ON TABLE agent_capabilities IS
    'Lo que puede hacer el computador de cada agente (lo revisa el agente en cada reporte): consentimiento y herramientas de captura, permisos y modo monitor.';
COMMENT ON COLUMN agent_capabilities.id IS 'Identificador.';
COMMENT ON COLUMN agent_capabilities.home_network_id IS 'Red de Mi Wi-Fi del agente (o NULL si es el sensor de una red del equipo).';
COMMENT ON COLUMN agent_capabilities.network_id IS 'Red del equipo cuyo sensor es este agente (o NULL si es de Mi Wi-Fi).';
COMMENT ON COLUMN agent_capabilities.platform IS 'Sistema operativo (Windows, Linux).';
COMMENT ON COLUMN agent_capabilities.agent_version IS 'Versión del agente que lo informó.';
COMMENT ON COLUMN agent_capabilities.elevated IS 'TRUE si el agente corre como administrador (root en Linux).';
COMMENT ON COLUMN agent_capabilities.capture_consent IS
    'TRUE si en ese computador se permitieron las capturas técnicas (comando capture-consent on). Sin esto el agente rechaza toda captura.';
COMMENT ON COLUMN agent_capabilities.npcap IS 'TRUE si Npcap está instalado y el agente puede usarlo.';
COMMENT ON COLUMN agent_capabilities.pktmon IS 'TRUE si pktmon (Windows 10/11) está disponible y el agente tiene permisos para usarlo.';
COMMENT ON COLUMN agent_capabilities.raw_socket IS 'TRUE si el agente puede abrir un socket sin procesar en Windows (administrador).';
COMMENT ON COLUMN agent_capabilities.packet_socket IS 'TRUE si el agente puede abrir un socket de paquetes en Linux (root).';
COMMENT ON COLUMN agent_capabilities.monitor_mode IS
    'Si el adaptador Wi-Fi declara modo monitor: SUPPORTED, UNSUPPORTED o UNKNOWN. WiFiSense no captura en modo monitor.';
COMMENT ON COLUMN agent_capabilities.capture_interfaces IS 'Interfaces de red en las que el agente podría capturar.';
COMMENT ON COLUMN agent_capabilities.reported_at IS 'Cuándo lo revisó el agente por última vez.';
