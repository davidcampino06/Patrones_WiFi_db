-- Connection tests an end user runs from Mi Wi-Fi on one of their networks. The browser measures latency, jitter
-- and speeds against the WiFiSense server; the AI grades the result. The grade stays NULL when the AI service was
-- unavailable, so the measurement is kept and nothing is invented.
CREATE TABLE connection_tests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_network_id  BIGINT           NOT NULL,
    latency_ms       DOUBLE PRECISION NOT NULL,
    jitter_ms        DOUBLE PRECISION NOT NULL,
    download_mbps    DOUBLE PRECISION NOT NULL,
    upload_mbps      DOUBLE PRECISION NOT NULL,
    quality_score    SMALLINT,
    quality_grade    VARCHAR(10),
    quality_details  JSONB,
    created_at       TIMESTAMPTZ      NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_connection_tests_network FOREIGN KEY (home_network_id) REFERENCES home_networks (id) ON DELETE CASCADE,
    CONSTRAINT ck_connection_tests_latency CHECK (latency_ms > 0 AND latency_ms <= 10000),
    CONSTRAINT ck_connection_tests_jitter CHECK (jitter_ms >= 0 AND jitter_ms <= 10000),
    CONSTRAINT ck_connection_tests_speeds CHECK (download_mbps BETWEEN 0 AND 10000 AND upload_mbps BETWEEN 0 AND 10000),
    CONSTRAINT ck_connection_tests_score CHECK (quality_score BETWEEN 0 AND 100),
    CONSTRAINT ck_connection_tests_grade CHECK (quality_grade IN ('EXCELLENT', 'GOOD', 'FAIR', 'POOR')),
    CONSTRAINT ck_connection_tests_quality_complete CHECK ((quality_score IS NULL) = (quality_grade IS NULL))
);

-- History of one network, newest first (Mi Wi-Fi shows the latest tests).
CREATE INDEX idx_connection_tests_network_time ON connection_tests (home_network_id, created_at DESC);
